// Downloads every photo listed in scripts/photos.json from the Unsplash CDN as
// WebP at each requested width (optional per photo: `quality`, and imgix `params`
// such as a portrait crop), then regenerates src/data/photos.generated.ts
// (dimensions + credits) and CREDITS.md. Run with: npm run photos
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'src/assets/images')
const photos = JSON.parse(await readFile(join(root, 'scripts/photos.json'), 'utf8'))
const force = process.argv.includes('--force')

/** Reads width/height from a WebP buffer (VP8, VP8L or VP8X). */
function webpSize(buf) {
  const chunk = buf.toString('ascii', 12, 16)
  if (chunk === 'VP8X') return { width: 1 + buf.readUIntLE(24, 3), height: 1 + buf.readUIntLE(27, 3) }
  if (chunk === 'VP8L') {
    const bits = buf.readUInt32LE(21)
    return { width: (bits & 0x3fff) + 1, height: ((bits >> 14) & 0x3fff) + 1 }
  }
  return { width: buf.readUInt16LE(26) & 0x3fff, height: buf.readUInt16LE(28) & 0x3fff }
}

async function download(url, file) {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${res.status} for ${url}`)
  const buf = Buffer.from(await res.arrayBuffer())
  await writeFile(file, buf)
  return buf
}

await mkdir(outDir, { recursive: true })
await mkdir(join(root, 'src/data'), { recursive: true })
const meta = {}

for (const p of photos) {
  const largest = Math.max(...p.widths)
  let size
  for (const w of p.widths) {
    const file = join(outDir, `${p.name}-${w}.webp`)
    const buf =
      existsSync(file) && !force
        ? await readFile(file)
        : await download(
            `https://images.unsplash.com/photo-${p.id}?w=${w}&q=${p.quality ?? (w >= 1200 ? 55 : 68)}&fm=webp&${p.params ?? 'fit=max'}`,
            file,
          )
    if (w === largest) size = webpSize(buf)
  }
  meta[p.name] = {
    ...size,
    photographer: p.photographer,
    profileUrl: `https://unsplash.com/@${p.username}`,
    sourceUrl: `https://unsplash.com/photos/${p.slug}`,
  }
  console.log(`✓ ${p.name} (${size.width}×${size.height})`)
}

// Open Graph image: 1200×630 crop of the first (hero) photo.
const hero = photos[0]
await download(
  `https://images.unsplash.com/photo-${hero.id}?w=1200&h=630&fit=crop&crop=entropy&q=75&fm=jpg`,
  join(root, 'public/og-image.jpg'),
)

const ts = `// Generated by scripts/fetch-photos.mjs — do not edit by hand.
// Add or swap photos in scripts/photos.json, then run \`npm run photos\`.
import type { PhotoMeta } from '../types'

export const photoMeta = ${JSON.stringify(meta, null, 2)} as const satisfies Record<string, PhotoMeta>

export type PhotoName = keyof typeof photoMeta
`
await writeFile(join(root, 'src/data/photos.generated.ts'), ts)

const unique = [...new Map(photos.map((p) => [p.slug, p])).values()]
const md = `# Photo credits

Every photo on this site is from [Unsplash](https://unsplash.com) and used under the
[Unsplash License](https://unsplash.com/license) (free for commercial use, no permission needed).
Thank you to the photographers below.

| Used for | Photographer | Source |
| --- | --- | --- |
${unique
  .map(
    (p) =>
      `| \`${p.name}\` | [${p.photographer}](https://unsplash.com/@${p.username}) | [unsplash.com/photos/${p.slug}](https://unsplash.com/photos/${p.slug}) |`,
  )
  .join('\n')}

Photos are downloaded and converted to WebP by \`scripts/fetch-photos.mjs\`.
`
await writeFile(join(root, 'CREDITS.md'), md)
console.log(`\nWrote ${photos.length} photos, photos.generated.ts and CREDITS.md`)
